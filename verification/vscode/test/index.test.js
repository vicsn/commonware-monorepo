'use strict';
// Tests of the span index on a synthetic file and on the repository's own extraction.

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const { Index, parse, isGenerated } = require('../lib/index');

const REPO = path.resolve(__dirname, '../../..');
const EXTRACTION = path.join(
  REPO,
  'verification/symbolic/proofs/lean/CommonwareSymbolic/Extraction',
);

function load() {
  const files = fs
    .readdirSync(EXTRACTION)
    .filter((f) => f.endsWith('.lean'))
    .map((f) => path.join(EXTRACTION, f))
    .map((p) => ({ path: p, text: fs.readFileSync(p, 'utf8') }));
  return Index.build(files);
}

function rust(rel) {
  const file = path.join(REPO, rel);
  return { file, lines: fs.readFileSync(file, 'utf8').split('\n') };
}

/** The 1-based line of `rel` that first contains `needle`. */
function lineOf(rel, needle) {
  const { lines } = rust(rel);
  const i = lines.findIndex((l) => l.includes(needle));
  assert.ok(i >= 0, `${needle} not in ${rel}`);
  return i + 1;
}

test('parses every comment form that Aeneas writes', () => {
  const text = [
    '-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS',
    'namespace demo',
    '/-- Trait declaration: [demo::Terms]',
    "    Source: 'src/a.rs', lines 10:0-28:1 -/",
    'structure Terms (Self : Type _) where',
    '/-- [demo::count]: loop body 0:',
    "    Source: 'src/a.rs', lines 63:4-68:5 -/",
    '@[rust_loop_body]',
    'def count_loop.body (x : U64) :',
    '/-- [demo::{impl core::convert::From<[u8; 32]> for demo::Key}::from]:',
    "    Source: 'src/a.rs', lines 61:9-61:16",
    '    Visibility: public -/',
    '@[reducible] def Key.Insts.CoreConvertFrom.from',
    '  : RustM Key := do',
    'end demo',
  ].join('\n');
  assert.ok(isGenerated(text));
  const entries = parse(text);
  assert.deepEqual(
    entries.map((e) => [e.kind, e.rustPath, e.fullName, e.start.line, e.end.col]),
    [
      ['trait', 'demo::Terms', 'demo.Terms', 10, 1],
      ['loop body', 'demo::count', 'demo.count_loop.body', 63, 5],
      [
        'item',
        'demo::{impl core::convert::From<[u8; 32]> for demo::Key}::from',
        'demo.Key.Insts.CoreConvertFrom.from',
        61,
        16,
      ],
    ],
  );
  assert.equal(entries[2].declLine, 12);
});

test('resolves every source path of the extraction to a file', () => {
  const index = load();
  assert.deepEqual(index.unresolved, []);
  assert.ok(index.entries.length > 150, `only ${index.entries.length} declarations`);
  for (const e of index.entries) {
    assert.ok(fs.existsSync(e.rustFile), `${e.fullName}: ${e.rustFile}`);
  }
});

test('the span of each named item starts at that item', () => {
  // Spans are 1-based: the first line of a function's span holds its name.
  const index = load();
  let checked = 0;
  for (const e of index.entries) {
    if (e.kind !== 'item' || e.rustPath.includes('{')) continue;
    const name = e.rustPath.split('::').pop();
    const lines = fs.readFileSync(e.rustFile, 'utf8').split('\n');
    assert.ok(lines[e.start.line - 1].includes(name), `${e.rustPath} at ${e.start.line}`);
    checked++;
  }
  assert.ok(checked > 50, `only ${checked} items checked`);
});

test('a Rust function maps to its generated definition', () => {
  const index = load();
  const rel = 'verification/symbolic/src/inclusion.rs';
  const { file, lines } = rust(rel);
  const start = lineOf(rel, 'pub(crate) fn verify_element_inclusion');
  const expected = 'commonware_symbolic.inclusion.verify_element_inclusion';
  // On the signature, inside the body, and on the doc comment above it.
  for (const line of [start, start + 8, start - 2]) {
    const hit = index.atRust(file, line, 4, lines);
    assert.equal(hit && hit.primary.fullName, expected, `line ${line}`);
  }
  const hit = index.atRust(file, start, 4, lines);
  const generated = fs.readFileSync(hit.primary.leanFile, 'utf8').split('\n');
  assert.match(generated[hit.primary.declLine], /^def inclusion\.verify_element_inclusion$/);
});

test('a production file included by path maps to its extraction', () => {
  const index = load();
  const rel = 'storage/src/merkle/proof/reconstruct.rs';
  const { file, lines } = rust(rel);
  const line = lineOf(rel, 'pub(crate) fn reconstruct<');
  const hit = index.atRust(file, line + 3, 8, lines);
  assert.equal(hit.primary.fullName, 'commonware_symbolic.reconstruct.reconstruct');
});

test('inside a loop the function comes first and its loop parts follow', () => {
  const index = load();
  const loops = index.entries.filter((e) => e.kind === 'loop body');
  assert.ok(loops.length > 0);
  const body = loops[0];
  const hit = index.atRust(body.rustFile, body.start.line + 1, 8, null);
  assert.equal(hit.primary.kind, 'item');
  assert.ok(hit.primary.start.line <= body.start.line);
  const kinds = hit.all.map((e) => e.kind);
  assert.ok(kinds.includes('loop') && kinds.includes('loop body'), kinds.join(', '));
});

test('a line outside every span maps to nothing', () => {
  const index = load();
  const rel = 'verification/symbolic/src/inclusion.rs';
  const { file, lines } = rust(rel);
  assert.equal(index.atRust(file, 1, 0, lines), null);
});

test('a Lean name and a line of generated Lean map back to the Rust', () => {
  const index = load();
  const [byName] = index.byName('inclusion.verify_element_inclusion');
  assert.equal(byName.rustFile, fs.realpathSync.native(rust('verification/symbolic/src/inclusion.rs').file));
  assert.deepEqual(index.byName('commonware_symbolic.inclusion.verify_element_inclusion'), [byName]);
  assert.equal(index.atLean(byName.leanFile, byName.declLine + 5), byName);
  assert.equal(index.atLean(byName.leanFile, byName.commentLine), byName);
});
