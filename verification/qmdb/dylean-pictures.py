def normalize(text):
    return ' '.join(text.split())


@dataclass
class Elaboration:
    """Normalized Lean output per appended command, and the axioms of every audited theorem."""

    outputs: dict
    axioms: dict

    def statement(self, name):
        output = self.outputs[f'#check @{name}']
        match = re.fullmatch(rf'@?{re.escape(name)} : (.+)', output)
        require(match, f'unexpected #check output for {name}: {output}')
        return match.group(1)

    def definition(self, name):
        output = self.outputs[f'#print {name}']
        match = re.fullmatch(rf'(?:@\[[^\]]*\] )?def {re.escape(name)} : (.+?) := (.+)', output)
        require(match, f'unexpected #print output for {name}: {output}')
        return match.group(2)

    def audited(self, name):
        require(name in self.axioms, f'{name} has no axiom audit')
        extra = self.axioms[name] - STANDARD_AXIOMS
        require(not extra, f'{name} depends on non-standard axioms {sorted(extra)}')


def elaborate(source, commands, toolchain, lean_path, cwd):
    """Elaborate `source` followed by `commands` and collect one message per command."""
    text = source if source.endswith('\n') else source + '\n'
    first = text.count('\n') + 1
    text += ''.join(command + '\n' for command in commands)
    run = subprocess.run(['lean', f'+{toolchain}', '--json', '--stdin'], input=text, cwd=cwd,
                         env={**os.environ, 'LEAN_PATH': lean_path}, capture_output=True,
                         text=True)
    by_line, errors = {}, []
    for raw in run.stdout.splitlines():
        try:
            message = json.loads(raw)
        except json.JSONDecodeError:
            errors.append(raw)
            continue
        line = message['pos']['line']
        if message['severity'] == 'error':
            errors.append(f'line {line}: {message["data"]}')
        by_line.setdefault(line, []).append(normalize(message['data']))
    require(run.returncode == 0 and not errors,
            'Lean failed:\n' + '\n'.join(errors or [run.stderr.strip()]))
    outputs = {}
    for offset, command in enumerate(commands):
        messages = by_line.get(first + offset, [])
        require(len(messages) == 1, f'expected one message for {command}, got {messages}')
        outputs[command] = messages[0]
    axioms = {}
    for messages in by_line.values():
        for message in messages:
            match = re.fullmatch(r"'([^']+)' depends on axioms: \[([^\]]*)\]", message)
            if match:
                axioms[match.group(1)] = set(filter(None, match.group(2).split(', ')))
    return Elaboration(outputs, axioms)


