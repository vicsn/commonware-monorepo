'use strict';
// Map between Rust source spans and the Lean declarations that Aeneas generates for them.
//
// Aeneas writes a doc comment above every generated declaration:
//
//   /-- [crate::module::item]: loop 0:
//       Source: 'src/module.rs', lines 24:0-52:1 -/
//
// The path in brackets names the Rust item, the label after it says which part of the item the
// declaration is (a loop, a loop body, a trait declaration or implementation), and the source
// path is relative to the root of the crate that Charon read. Lines are 1-based, columns 0-based.

const fs = require('fs');
const path = require('path');

const MARKER = 'AUTOMATICALLY GENERATED BY AENEAS';
const SOURCE = /Source: '([^']+)', lines (\d+):(\d+)-(\d+):(\d+)/;
const MODIFIERS = new Set([
  'noncomputable', 'partial', 'private', 'protected', 'public', 'unsafe', 'nonrec',
]);

/** Whether `text` is a file that Aeneas generated. */
function isGenerated(text) {
  return text.slice(0, 400).includes(MARKER);
}

/** The text between the first `[` of `s` and its matching `]`, or null. */
function bracketed(s) {
  const open = s.indexOf('[');
  if (open < 0) return null;
  let depth = 0;
  for (let i = open; i < s.length; i++) {
    if (s[i] === '[') depth++;
    else if (s[i] === ']' && --depth === 0) return { inner: s.slice(open + 1, i), end: i + 1 };
  }
  return null;
}

/** The kind of a declaration from the words around the bracketed Rust path of its comment. */
function kindOf(before, after) {
  if (/Trait declaration/.test(before)) return 'trait';
  if (/Trait implementation/.test(before)) return 'impl';
  if (/loop body/.test(after)) return 'loop body';
  if (/loop/.test(after)) return 'loop';
  return 'item';
}

/** The keyword and name of the declaration that starts at or after line `i`, or null. */
function declaration(lines, i) {
  for (; i < lines.length; i++) {
    let line = lines[i].trim();
    while (line.startsWith('@[')) {
      const close = line.indexOf(']');
      if (close < 0) break;
      line = line.slice(close + 1).trim();
    }
    if (line === '') continue;
    const words = line.split(/\s+/);
    let w = 0;
    while (w < words.length && MODIFIERS.has(words[w])) w++;
    if (w + 1 >= words.length) return null;
    return { keyword: words[w], name: words[w + 1], line: i };
  }
  return null;
}

/**
 * The declarations of one generated Lean file, in order. Each has the Rust path and part it
 * comes from, the source span as written, and the Lean name with and without its namespace.
 */
function parse(text) {
  const lines = text.split('\n');
  const namespaces = [];
  const entries = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const ns = /^namespace\s+(\S+)/.exec(line);
    if (ns) {
      namespaces.push(ns[1]);
      continue;
    }
    if (/^end\s+(\S+)/.test(line) && namespaces.length > 0) {
      namespaces.pop();
      continue;
    }
    if (!line.startsWith('/--')) continue;
    let close = i;
    while (close < lines.length && !lines[close].includes('-/')) close++;
    const comment = lines.slice(i, close + 1).join('\n');
    const source = SOURCE.exec(comment);
    const rust = bracketed(comment);
    if (!source || !rust) {
      i = close;
      continue;
    }
    const before = comment.slice(0, comment.indexOf('['));
    const after = comment.slice(rust.end, comment.indexOf('Source:'));
    const decl = declaration(lines, close + 1);
    if (!decl) {
      i = close;
      continue;
    }
    const prefix = namespaces.join('.');
    entries.push({
      rustPath: rust.inner,
      kind: kindOf(before, after),
      file: source[1],
      start: { line: Number(source[2]), col: Number(source[3]) },
      end: { line: Number(source[4]), col: Number(source[5]) },
      keyword: decl.keyword,
      leanName: decl.name,
      fullName: prefix ? `${prefix}.${decl.name}` : decl.name,
      commentLine: i,
      declLine: decl.line,
    });
    i = decl.line;
  }
  return entries;
}

/** `p` with symbolic links resolved and its case made canonical, when it exists. */
function canonical(p) {
  try {
    return fs.realpathSync.native(p);
  } catch {
    return path.resolve(p);
  }
}

/**
 * The crate root that the source paths of `entries` are relative to: the nearest ancestor of the
 * generated file under which most of the distinct source files exist, or null.
 */
function crateRoot(leanFile, entries, exists = fs.existsSync) {
  const files = [...new Set(entries.map((e) => e.file))];
  if (files.length === 0) return null;
  let dir = path.dirname(path.resolve(leanFile));
  for (;;) {
    const found = files.filter((f) => exists(path.resolve(dir, f))).length;
    if (2 * found >= files.length && found > 0) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

/** Whether a Rust line can sit between an item's doc comment or attributes and the item. */
function preamble(line) {
  const t = line.trim();
  return t === '' || t.startsWith('//') || t.startsWith('#[') || t.startsWith('#![');
}

/** The number of lines that a span covers, for picking the innermost span. */
function size(e) {
  return (e.end.line - e.start.line) * 100000 + (e.end.col - e.start.col);
}

function onLine(e, line) {
  return e.start.line <= line && line <= e.end.line;
}

/** Whether a span on one line, such as a name in a derive list, holds column `col`. */
function under(e, line, col) {
  return e.start.line === line && e.end.line === line && e.start.col <= col && col <= e.end.col;
}

function innermostFirst(entries) {
  return entries.sort((a, b) => size(a) - size(b));
}

class Index {
  constructor(entries) {
    this.entries = entries;
    this.byRust = new Map();
    this.byLean = new Map();
    for (const e of entries) {
      if (!this.byRust.has(e.rustFile)) this.byRust.set(e.rustFile, []);
      this.byRust.get(e.rustFile).push(e);
      if (!this.byLean.has(e.leanFile)) this.byLean.set(e.leanFile, []);
      this.byLean.get(e.leanFile).push(e);
    }
  }

  /**
   * Index generated files given as `{ path, text }`. Files that Aeneas did not generate are
   * skipped, as are files whose crate root cannot be found.
   */
  static build(files, exists = fs.existsSync) {
    const entries = [];
    const unresolved = [];
    for (const { path: leanFile, text } of files) {
      if (!isGenerated(text)) continue;
      const parsed = parse(text);
      const root = crateRoot(leanFile, parsed, exists);
      if (root === null) {
        if (parsed.length > 0) unresolved.push(leanFile);
        continue;
      }
      const lean = canonical(leanFile);
      for (const e of parsed) {
        entries.push({ ...e, leanFile: lean, rustFile: canonical(path.resolve(root, e.file)) });
      }
    }
    const index = new Index(entries);
    index.unresolved = unresolved;
    return index;
  }

  /**
   * The declarations generated from the Rust at 1-based `line` and 0-based `col` of `rustFile`.
   * `primary` is the innermost whole item there (not a loop), and `all` lists the declarations
   * that hold the position, `primary` first. A span on one line, such as a name in a derive
   * list, counts only under its columns. On a line of an item's doc comment or attributes, the
   * item below comes before the items around it. `lines` is the Rust file's text, split into
   * lines.
   */
  atRust(rustFile, line, col, lines) {
    const candidates = this.byRust.get(canonical(rustFile)) || [];
    let all = innermostFirst(candidates.filter((e) => under(e, line, col)));
    const around = innermostFirst(
      candidates.filter((e) => onLine(e, line) && e.start.line !== e.end.line),
    );
    if (all.length === 0 && lines && preamble(lines[line - 1] || '')) {
      let next = line;
      while (next <= lines.length && preamble(lines[next - 1])) next++;
      all = innermostFirst(candidates.filter((e) => e.start.line === next)).reverse();
    }
    all = [...all, ...around.filter((e) => !all.includes(e))];
    if (all.length === 0) {
      all = innermostFirst(candidates.filter((e) => e.start.line === line && e.end.line === line));
    }
    if (all.length === 0) return null;
    const whole = all.filter((e) => e.kind !== 'loop' && e.kind !== 'loop body');
    const primary = whole.length > 0 ? whole[0] : all[0];
    const rest = all.filter((e) => e !== primary);
    return { primary, all: [primary, ...rest] };
  }

  /**
   * The declarations whose span starts on 1-based `line` of `rustFile`, such as a function on the
   * line of its signature: whole items first, then loops. A span on one line counts only under its
   * columns, so on a derive list only the name under `col` does.
   */
  startingAt(rustFile, line, col) {
    const candidates = this.byRust.get(canonical(rustFile)) || [];
    const starting = candidates.filter(
      (e) => e.start.line === line && (e.end.line !== line || under(e, line, col)),
    );
    const loop = (e) => e.kind === 'loop' || e.kind === 'loop body';
    return starting.sort((a, b) => loop(a) - loop(b) || size(b) - size(a));
  }

  /**
   * The declarations named `word`: the full or namespace-relative name of a generated
   * declaration, or else any whose name ends in `.word`.
   */
  byName(word) {
    const exact = this.entries.filter((e) => e.fullName === word || e.leanName === word);
    if (exact.length > 0) return exact;
    return this.entries.filter((e) => e.fullName.endsWith(`.${word}`));
  }

  /** The generated declaration of `leanFile` whose comment or body holds 0-based `line`. */
  atLean(leanFile, line) {
    const entries = this.byLean.get(canonical(leanFile)) || [];
    let found = null;
    for (const e of entries) {
      if (e.commentLine <= line) found = e;
      else break;
    }
    return found;
  }
}

module.exports = { Index, parse, crateRoot, isGenerated, bracketed };
