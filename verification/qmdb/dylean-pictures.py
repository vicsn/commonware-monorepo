@dataclass
class Claim:
    theorem: str
    flags: list
    subject: str
    signature: str
    accepted: bool
    reason: str


@dataclass
class Certificates:
    members: int
    quorum: int
    signers: list
    claims: list


def bls_commands(source):
    theorems = re.findall(r'^theorem (\w+)', source, re.M)
    definitions = re.findall(r'^(?:noncomputable )?(?:def|abbrev|instance) (\w+)', source, re.M)
    commands = [f'#check @Bls.Sanity.{name}' for name in theorems]
    commands += [f'#print axioms Bls.Sanity.{name}' for name in theorems]
    commands += [f'#print Bls.Sanity.{name}' for name in definitions]
    commands += [f'#check @{name}' for name in BLS_STATEMENTS]
    commands += [f'#print axioms {name}' for name in BLS_STATEMENTS]
    return theorems, commands


BASIS = r'Commonware\.Symbolic\.Linear\.basis (\d+)'


def own_keys(listed, what):
    """The members of a list of keys in which each member holds its own key."""
    keys = listed.split(', ')
    for index, key in enumerate(keys):
        match = re.fullmatch(BASIS, key)
        require(match and int(match.group(1)) == index,
                f'{what} is not own keys in order: {listed}')
    return len(keys)


def bits(listed):
    flags = listed.split(', ')
    require(all(flag in ('true', 'false') for flag in flags), f'unexpected flags: {listed}')
    return [flag == 'true' for flag in flags]


BLS_VERDICT = re.compile(
    r'(?:∀ \((\w+) : (.+?)\), )?Bls\.Sanity\.verdict \(Bls\.Sanity\.flags \[([a-z, ]+)\] \S+\) '
    r'Bls\.Sanity\.(\w+) (\w+|\(Bls\.Sanity\.signature Bls\.Sanity\.(\w+)\)) = '
    r'Aeneas\.Std\.RustM\.ok (none|\(some \(Bls\.Protocol\.Event\.certify Bls\.Sanity\.ns '
    r'Bls\.Sanity\.(\w+) \[([a-z, ]+)\] \{ members := (\d+)#u64, quorum := (\d+)#u64 \}\)\))')
SIG_TYPE = ('Commonware.Symbolic.Linear.Sig (Commonware.Symbolic.Linear.Input '
            '(Aeneas.Std.Slice Aeneas.Std.U8))')


def bls(lean, theorems):
    for name, expected in BLS_DEFINITIONS.items():
        require(lean.definition(name) == expected, f'{name} changed: {lean.definition(name)}')
    # The committee: each member holds its own key, and the hash keeps inputs apart.
    committee = lean.definition('Bls.Sanity.committee')
    match = re.fullmatch(r'\{ Hashed := Commonware\.Symbolic\.Linear\.Input '
                         r'\(Aeneas\.Std\.Slice Aeneas\.Std\.U8\), hash := id, '
                         r'keys := \[(.+)\], bounded := \S+ \}', committee)
    require(match, f'unexpected committee: {committee}')
    members = own_keys(match.group(1), 'the committee')
    require(2 <= members <= 6, f'cannot lay out a committee of {members}')
    quorum = members - (members - 1) // 3
    # The signature of the drawn certificate: some members over the subject it is given.
    signature = lean.definition('Bls.Sanity.signature')
    match = re.fullmatch(r'fun (\w+) => Commonware\.Symbolic\.Linear\.term '
                         r'\(Commonware\.Symbolic\.Linear\.total \[(.+)\]\) '
                         r'\(Commonware\.Symbolic\.Linear\.Input\.message Bls\.Sanity\.ns \1\)',
                         signature)
    require(match, f'unexpected signature: {signature}')
    signers = list(range(own_keys(match.group(2), 'the signature')))

    for name, expected in BLS_STATEMENTS.items():
        require(lean.statement(name) == expected, f'{name} changed: {lean.statement(name)}')
        lean.audited(name)

    claims = {}
    for theorem in theorems:
        full = f'Bls.Sanity.{theorem}'
        statement = lean.statement(full)
        lean.audited(full)
        match = BLS_VERDICT.fullmatch(statement)
        if not match:
            require(theorem in BLS_NOT_DRAWN, f'{full} is neither drawn nor checked: {statement}')
            continue
        require(theorem in BLS_VIEWS, f'{full} is a new verdict theorem; add it to BLS_VIEWS')
        binder, binder_type, listed, subject = match.group(1, 2, 3, 4)
        term, signed, verdict = match.group(5, 6, 7)
        flags = bits(listed)
        named = [index for index, flag in enumerate(flags) if flag]
        spans, enough = len(flags) == members, len(named) >= quorum
        if binder:
            require(term == binder and binder_type == SIG_TYPE,
                    f'{full} has an unrecognized signature {term}')
            kind = 'any'
        else:
            require(signed is not None, f'{full} has an unrecognized signature {term}')
            kind = signed
        accepted = verdict != 'none'
        if accepted:
            event = (match.group(8), bits(match.group(9)), int(match.group(10)),
                     int(match.group(11)))
            require(event == (subject, flags, members, quorum), f'{full} logs {event}')
            require(spans and enough and kind == subject and named == signers,
                    f'{full} accepts a certificate that the committee should not accept')
            reason = 'quorum'
        elif not spans:
            reason = 'wrong length'
        elif not enough:
            reason = 'below quorum'
        else:
            require(kind != 'any' and (kind != subject or named != signers),
                    f'{full} rejects a certificate for an unrecognized reason')
            reason = 'other subject' if kind != subject else 'other signers'
        claims[theorem] = Claim(full, flags, subject, kind, accepted, reason)
    missing = [name for name in BLS_VIEWS if name not in claims]
    require(not missing, f'drawn theorems not found in the BLS sanity checks: {missing}')
    return Certificates(members, quorum, signers, [claims[name] for name in BLS_VIEWS])


# Rendering

def esc(text):
    return html.escape(text, quote=True)


def num(value):
    return str(int(value)) if float(value).is_integer() else f'{value:.1f}'


def text(x, y, content, cls='label', anchor='middle'):
    return (f'<text x="{num(x)}" y="{num(y)}" class="{cls}" '
            f'text-anchor="{anchor}">{esc(content)}</text>')


def rect(x, y, width, height, cls):
    return (f'<rect x="{num(x)}" y="{num(y)}" width="{num(width)}" height="{num(height)}" '
            f'rx="5" class="{cls}"/>')


def box(x, y, width, height, cls, content):
    return rect(x, y, width, height, cls) + text(x + width / 2, y + height / 2 + 5, content)


def line(x1, y1, x2, y2, cls='wire'):
    return f'<path class="{cls}" d="M{num(x1)} {num(y1)} L{num(x2)} {num(y2)}"/>'


def circle(x, y, cls, radius=5):
    return f'<circle cx="{num(x)}" cy="{num(y)}" r="{num(radius)}" class="{cls}"/>'


def svg(title, description, body):
    return (f'<svg role="img" aria-label="{esc(title)}. {esc(description)}" '
            f'viewBox="0 0 470 242"><title>{esc(title)}</title>'
            f'<desc>{esc(description)}</desc>{body}</svg>')


def figure(anchor, heading, views, caption):
    select = ''
    if len(views) > 1:
        options = ''.join(f'<option value="{index}">{esc(title)}</option>'
                          for index, (title, _) in enumerate(views))
        select = (f'<label class="scenario">View <select id="{anchor}-view">{options}'
                  '</select></label>')
    frames = ''.join(f'<div class="scenario-frame"{" hidden" if index else ""}>{image}</div>'
                     for index, (_, image) in enumerate(views))
    return (f'<figure class="proof-graphic"><h4 id="{anchor}">{esc(heading)}</h4>{select}{frames}'
            f'<figcaption>{caption}</figcaption></figure>')


def listing(names):
    return names[0] if len(names) == 1 else ', '.join(names[:-1]) + ' and ' + names[-1]


SIBLING_TITLES = {'honest': 'honest path', 'any': 'any siblings', 'extra': 'unused sibling'}


def merkle_view(model, attempt):
    height, leaves = model.height, model.leaves
    top, bottom = 53, 118

    def x(level, index):
        return 19 + 184 * (index + 0.5) / 2 ** level

    def y(level):
        return top + (bottom - top) * level / height

    # The honest path reads the sibling of each node from the claimed leaf up to the peak.
    siblings = set()
    index = attempt.location
    for level in range(height, 0, -1):
        if attempt.siblings != 'any':
            siblings.add((level, index ^ 1))
        index //= 2
    body = [text(20, 24, f'Trusted snapshot · height {height}', 'heading', 'start')]
    for level in range(height):
        for index in range(2 ** level):
            for child in (2 * index, 2 * index + 1):
                body.append(line(x(level, index), y(level), x(level + 1, child), y(level + 1)))
    for level in range(height):
        for index in range(2 ** level):
            if (level, index) in siblings:
                body.append(circle(x(level, index), y(level), 'cursor', 9))
            body.append(circle(x(level, index), y(level), 'plain'))
    claimed = 'hit' if attempt.accepted else 'given'
    for location, item in enumerate(leaves):
        cx = x(height, location)
        if (height, location) in siblings:
            body.append(rect(cx - 17, 106, 34, 31, 'cursor'))
        cls = claimed if location == attempt.location else 'plain'
        body.append(rect(cx - 13, 110, 26, 23, cls))
        body.append(text(cx, 126.5, str(location)))
        body.append(text(cx, 153, item, 'minor'))
    sibling_count = height + (attempt.siblings == 'extra')
    if attempt.siblings == 'any':
        supplied = 'Any sibling sequence'
    elif attempt.siblings == 'honest':
        supplied = f'Honest path · {sibling_count} sibling{"s" if sibling_count != 1 else ""}'
    else:
        supplied = 'Honest path + 1 unused'
    submitted = f'Attacker submits {attempt.item} at {attempt.location}'
    body.append(box(222, 43, 226, 34, 'plain', submitted))
    body.append(line(335, 77, 335, 101))
    body.append(box(222, 100, 226, 34, 'plain', supplied))
    body.append(line(335, 134, 335, 158))
    event = f'({height}, {attempt.location}, {attempt.item})'
    if attempt.accepted:
        body.append(box(201, 157, 255, 42, 'hit', f'client_step returns {event}'))
        consequence = f'Logged item = snapshot[{attempt.location}] = {attempt.item}'
    else:
        body.append(box(201, 157, 255, 42, 'given', 'client_step returns none'))
        consequence = 'No acceptance event is logged'
    body.append(text(20, 218, consequence, 'heading', 'start'))
    body.append(text(20, 236, f'Lean · {attempt.theorem}', 'minor', 'start'))
    title = f'{attempt.item} at {attempt.location} · {SIBLING_TITLES[attempt.siblings]}'
    if attempt.accepted:
        description = (f'The honest path for {attempt.item} at {attempt.location}. The extracted '
                       f'client step returns the acceptance {event}, which the client logs with '
                       'these siblings.')
    elif attempt.siblings == 'any':
        description = (f'{attempt.item} is not stored at {attempt.location}. The extracted client '
                       'step returns none for every sibling sequence.')
    else:
        description = (f'The honest path for {attempt.item} at {attempt.location} followed by one '
                       'unused sibling. The extracted client step returns none for every extra '
                       'sibling.')
    return title, svg(title, f'{description} Lean theorem {attempt.theorem}.', ''.join(body))


def merkle_figure(model):
    views = [merkle_view(model, attempt) for attempt in model.attempts]
    caption = (f'Each view restates a checked theorem about the extracted client step on the '
               f'{len(model.leaves)}-leaf snapshot that stores {listing(model.leaves)}. Dashed '
               'outlines mark the siblings of the honest path. By <code>attempt_reachable</code> '
               'every attempt is a reachable trace. By <code>client_authentication</code> any '
               'opening logged on such a trace names the snapshot height and an in-range location, '
               'and its item is the one stored there or the finder returns a collision. This '
               'snapshot hashes with DyLean’s constructor, which has no collisions, so by '
               '<code>collision_free_authentication</code> the logged item is the stored one.')
    return figure('pictures-merkle', 'Merkle · Authenticate a client event', views, caption)


def members_text(indices):
    if not indices:
        return 'no members'
    noun = 'Member' if len(indices) == 1 else 'Members'
    return f'{noun} {listing([str(index) for index in indices])}'


def bls_view(model, claim):
    named = [index for index, flag in enumerate(claim.flags) if flag]
    slots = max(model.members, len(claim.flags))
    step = min(38, 170 / slots)
    body = [text(20, 24, f'Trusted committee · {model.members} members · quorum {model.quorum}',
                 'heading', 'start'),
            text(20, 62, 'Signer flags', 'minor', 'start')]
    for index in range(slots):
        x = 20 + index * step
        if index >= model.members:
            body.append(rect(x - 3, 71, step - 2, 36, 'cursor'))
        flagged = index < len(claim.flags) and claim.flags[index]
        cls = ('hit' if claim.accepted else 'given') if flagged else 'plain'
        if index < len(claim.flags):
            body.append(rect(x, 74, step - 8, 30, cls))
            body.append(text(x + (step - 8) / 2, 94, str(index)))
    body.append(text(20, 132, f'{len(named)} named · {model.quorum} needed', 'minor', 'start'))
    flags = ''.join('1' if flag else '0' for flag in claim.flags)
    body.append(box(222, 43, 226, 34, 'plain', f'Attacker submits flags {flags}'))
    body.append(line(335, 77, 335, 101))
    if claim.signature == 'any':
        supplied = 'Any signature'
    else:
        supplied = f'{members_text(model.signers)} sign “{claim.signature}”'
    body.append(box(222, 100, 226, 34, 'plain', supplied))
    body.append(line(335, 134, 335, 158))
    if claim.accepted:
        body.append(box(201, 157, 255, 42, 'hit',
                        f'client_step returns ({model.members}, {model.quorum})'))
        consequence = f'{members_text(named)} signed “{claim.subject}” earlier'
    else:
        body.append(box(201, 157, 255, 42, 'given', 'client_step returns none'))
        consequence = 'No certificate is logged'
    body.append(text(20, 218, consequence, 'heading', 'start'))
    body.append(text(20, 236, f'Lean · {claim.theorem}', 'minor', 'start'))
    title = f'{members_text(named)} · {claim.reason}'
    if claim.reason == 'quorum':
        description = (f'{members_text(named)} of {model.members} signed “{claim.subject}” '
                       'and are named. The extracted client step returns the committee size and '
                       'its quorum, which the client logs with the flags.')
    elif claim.reason == 'below quorum':
        description = (f'{len(named)} named members are below the quorum of {model.quorum}. The '
                       'extracted client step returns none for every signature.')
    elif claim.reason == 'wrong length':
        description = (f'{len(claim.flags)} flags do not span the committee of {model.members}. '
                       'The extracted client step returns none for every signature.')
    else:
        description = (f'The signature of {members_text(model.signers).lower()} over '
                       f'“{claim.signature}” is submitted for “{claim.subject}”. The extracted '
                       'client step returns none.')
    return title, svg(title, f'{description} Lean theorem {claim.theorem}.', ''.join(body))


def bls_figure(model):
    views = [bls_view(model, claim) for claim in model.claims]
    caption = ('Each view restates a checked theorem about the extracted client step on a '
               f'committee of {model.members} members with their own keys, whose quorum is '
               f'{model.quorum}. Filled squares are the members that the certificate names. By '
               '<code>certificate_authentication</code> a certificate logged on a reachable trace '
               'has one flag per member and names the quorum, and every named member that '
               'registered its own key and was not compromised signed exactly that subject '
               'earlier, or the hash collides. This committee’s hash keeps inputs apart, so by '
               '<code>collision_free_authentication</code> those members signed.')
    return figure('pictures-bls', 'BLS · Authorize a certificate', views, caption)


def block(source, merkle_model, certificates):
    intro = ('These two pictures are generated from the statements that Lean prints for the '
             'DyLean sanity checks of both targets, so each view matches a checked theorem. '
             'Regenerate them with <code>python3 verification/qmdb/dylean-pictures.py</code>; '
             'with <code>--check</code> it fails when the page and those statements disagree.')
    return (f'{BEGIN} from {source}; edit the script, not this block -->\n'
            f'<section id="{SECTION}"><h2>{SECTION_TITLE}</h2>\n<p>{intro}</p>\n'
            f'<div class="proof-pair">\n{merkle_figure(merkle_model)}\n{bls_figure(certificates)}\n'
            f'</div>\n</section>\n{END}')


def splice(page, generated):
    if BEGIN in page:
        require(page.count(BEGIN) == 1 and page.count(END) == 1, 'duplicate generated markers')
        start = page.index(BEGIN)
        end = page.index(END, start) + len(END)
    else:
        require(page.count(PRECEDING) == 1, f'cannot find {PRECEDING}')
        close = '</section>\n'
        start = end = page.index(close, page.index(PRECEDING)) + len(close)
        generated += '\n'
    return page[:start] + generated + page[end:]


# Driver

def committed(branch, rel):
    try:
        return git('show', f'{branch}:{rel}')
    except subprocess.CalledProcessError:
        return None


def provenance(dylean, branch):
    # The last commit that changed the Lean sources, so that committing the page keeps it current.
    commit = git('log', '-1', '--format=%h', branch, '--', *SOURCES).decode().strip()
    dirty = [rel for rel in SOURCES if (dylean / rel).read_bytes() != committed(branch, rel)]
    source = f'{branch}@{commit}'
    if dirty:
        print(f'warning: {", ".join(dirty)} differ from {source}', file=sys.stderr)
        source += ' with uncommitted changes'
    return source


def derive(dylean):
    lean = dylean / LEAN
    build = lean / '.lake/build/lib/lean'
    compat = dylean / DYLEAN_BUILD
    for module in BRIDGE_MODULES:
        built = build / module_path(module).replace('.lean', '.olean')
        require(built.exists(), f'missing {built}; run verification/check.sh')
        require(built.stat().st_mtime >= (lean / module_path(module)).stat().st_mtime,
                f'{built} is older than its source; run verification/check.sh')
    require(compat.exists(), f'missing {compat}; run verification/check.sh')

    toolchain = assignment(dylean / TOOLCHAIN, 'lean_toolchain')
    source = (lean / SANITY).read_text()
    theorems, commands = merkle_commands(source)
    merkle_model = merkle(elaborate(source, commands, toolchain, lake_path(lean), lean), theorems)

    source = (lean / BLS_SANITY).read_text()
    theorems, commands = bls_commands(source)
    certificates = bls(elaborate(source, commands, toolchain, lake_path(lean), lean), theorems)
    return merkle_model, certificates


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true',
                        help='exit 1 if the report differs instead of writing it')
    parser.add_argument('--dylean', type=Path, help='DyLean worktree (default: the shared one)')
    parser.add_argument('--branch', default=BRANCH, help=f'DyLean branch (default: {BRANCH})')
    parser.add_argument('--report', type=Path, default=REPORT)
    args = parser.parse_args()
    dylean = (args.dylean or default_dylean()).resolve()
    try:
        merkle_model, certificates = derive(dylean)
        generated = block(provenance(dylean, args.branch), merkle_model, certificates)
        page = args.report.read_text()
        updated = splice(page, generated)
    except Mismatch as error:
        sys.exit(f'dylean-pictures: {error}')
    if args.check:
        if updated != page:
            sys.exit(f'dylean-pictures: {args.report.name} is out of date; run {sys.argv[0]}')
        print(f'{args.report.name} matches the Lean statements.')
    elif updated != page:
        args.report.write_text(updated)
        print(f'Updated the generated Hax → DyLean pictures in {args.report.name}.')
    else:
        print(f'{args.report.name} already matches the Lean statements.')


if __name__ == '__main__':
    main()
