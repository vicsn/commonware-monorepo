@dataclass
class Attempt:
    theorem: str
    item: str
    location: int
    siblings: str
    accepted: bool


@dataclass
class Merkle:
    height: int
    leaves: list
    attempts: list


def merkle_commands(source):
    theorems = re.findall(r'^theorem (\w+)', source, re.M)
    definitions = re.findall(r'^(?:noncomputable )?(?:def|abbrev|instance) (\w+)', source, re.M)
    commands = [f'#check @Qmdb.Sanity.{name}' for name in theorems]
    commands += [f'#print axioms Qmdb.Sanity.{name}' for name in theorems]
    commands += [f'#print Qmdb.Sanity.{name}' for name in definitions]
    commands += [f'#print {name}' for name in MERKLE_DEFINITIONS if 'Sanity' not in name]
    commands += [f'#check @{name}' for name in MERKLE_STATEMENTS if 'Sanity' not in name]
    commands += [f'#print axioms {name}' for name in MERKLE_STATEMENTS if 'Sanity' not in name]
    return theorems, commands


def ascii_item(lean, name):
    value = lean.definition(f'Qmdb.Sanity.{name}')
    match = re.fullmatch(r'Aeneas\.Std\.Slice\.from \[([^\]]*)\] \S+', value)
    require(match, f'{name} is not a byte literal: {value}')
    parts = match.group(1).split(', ')
    require(all(re.fullmatch(r'\d+#u8', part) for part in parts), f'{name} bytes: {value}')
    text = bytes(int(part[:-3]) for part in parts).decode('ascii')
    require(text.isalnum(), f'{name} is not a printable label: {text!r}')
    return text


def honest_location(lean, name, height):
    value = lean.definition(f'Qmdb.Sanity.{name}')
    match = re.fullmatch(r'Qmdb\.Verifier\.honestSiblings Commonware\.Symbolic\.symbolic '
                         r'Qmdb\.Sanity\.items (\d+) (\d+)#u64 \S+', value)
    require(match and int(match.group(1)) == height, f'{name} is not an honest opening: {value}')
    return int(match.group(2))


def extended_location(lean, name, height):
    value = lean.definition(f'Qmdb.Sanity.{name}')
    match = re.fullmatch(r'fun (\w+) => Aeneas\.Std\.Slice\.from \(Qmdb\.Verifier\.path '
                         r'Commonware\.Symbolic\.symbolic Qmdb\.Sanity\.items (\d+) '
                         r'\(2 \* \(2 \^ (\d+) - 1\)\) 0 (\d+) '
                         r'\+\+ \[\1\]\) ⋯', value)
    require(match and int(match.group(2)) == int(match.group(3)) == height,
            f'{name} is not an honest opening followed by one sibling: {value}')
    return int(match.group(4))


VERDICT = re.compile(
    r'(?:∀ \((\w+) : ([^()]+)\), )?Qmdb\.Sanity\.verdict Qmdb\.Sanity\.(\w+) (\d+)#u64 '
    r'(\S+|\([^()]*\)) = Aeneas\.Std\.RustM\.ok (none|\(some \{ height := (\d+)#u32, '
    r'location := (\d+)#u64, item := Qmdb\.Sanity\.(\w+) \}\))')


def merkle(lean, theorems):
    for name, expected in MERKLE_DEFINITIONS.items():
        require(lean.definition(name) == expected, f'{name} changed: {lean.definition(name)}')
    snapshot = lean.definition('Qmdb.Sanity.snapshot')
    # The snapshot hashes with DyLean's constructor, so the collision-free statement applies.
    match = re.fullmatch(r'\{ hash := DY\.Hash\.hash, height := (\d+)#u32, '
                         r'root := Qmdb\.Verifier\.honestRoot '
                         r'Commonware\.Symbolic\.symbolic Qmdb\.Sanity\.items (\d+), '
                         r'items := Qmdb\.Sanity\.items, siblings := fun (\w+) => '
                         r'Qmdb\.Verifier\.honestSiblings Commonware\.Symbolic\.symbolic '
                         r'Qmdb\.Sanity\.items (\d+) \3 \S+, honest := \S+ \}', snapshot)
    require(match and match.group(1) == match.group(2) == match.group(4),
            f'unexpected snapshot: {snapshot}')
    height = int(match.group(1))
    require(1 <= height <= 3, f'cannot lay out a snapshot of height {height}')
    items = lean.definition('Qmdb.Sanity.items')
    match = re.fullmatch(r'fun (\w+) => if ↑\1 = (\d+) then Qmdb\.Sanity\.(\w+) '
                         r'else Qmdb\.Sanity\.(\w+)', items)
    require(match, f'unexpected items: {items}')
    special, then, other = int(match.group(2)), match.group(3), match.group(4)
    names = {then: ascii_item(lean, then), other: ascii_item(lean, other)}
    leaves = [names[then if location == special else other] for location in range(2 ** height)]

    for name, expected in MERKLE_STATEMENTS.items():
        require(lean.statement(name) == expected, f'{name} changed: {lean.statement(name)}')
        lean.audited(name)

    attempts = {}
    for theorem in theorems:
        full = f'Qmdb.Sanity.{theorem}'
        statement = lean.statement(full)
        match = VERDICT.fullmatch(statement)
        if not match:
            require(full in MERKLE_STATEMENTS or theorem in MERKLE_NOT_DRAWN,
                    f'{full} is neither drawn nor checked: {statement}')
            lean.audited(full)
            continue
        require(theorem in MERKLE_VIEWS or theorem in MERKLE_OMITTED,
                f'{full} is a new verdict theorem; add it to MERKLE_VIEWS or MERKLE_OMITTED')
        lean.audited(full)
        binder, binder_type, item, location, term, verdict = match.group(1, 2, 3, 4, 5, 6)
        location = int(location)
        require(location < 2 ** height, f'{full} claims location {location} outside the snapshot')
        item = ascii_item(lean, item)
        if binder and term == binder and binder_type == 'Aeneas.Std.Slice DY.Bytes':
            siblings = 'any'
        elif not binder and (plain := re.fullmatch(r'Qmdb\.Sanity\.(\w+)', term)):
            siblings = 'honest'
            require(honest_location(lean, plain.group(1), height) == location,
                    f'{full} uses the honest path of another location')
        elif binder_type == 'DY.Bytes' and (
                applied := re.fullmatch(rf'\(Qmdb\.Sanity\.(\w+) {binder}\)', term or '')):
            siblings = 'extra'
            require(extended_location(lean, applied.group(1), height) == location,
                    f'{full} extends the honest path of another location')
        else:
            raise Mismatch(f'{full} has unrecognized siblings {term}')
        accepted = verdict != 'none'
        if accepted:
            event = (int(match.group(7)), int(match.group(8)), ascii_item(lean, match.group(9)))
            require(event == (height, location, item), f'{full} logs {event}')
            require(leaves[location] == item, f'{full} accepts an item that is not stored')
        elif siblings == 'any':
            require(leaves[location] != item, f'{full} rejects the stored item for any siblings')
        attempts[theorem] = Attempt(full, item, location, siblings, accepted)
    missing = [name for name in MERKLE_VIEWS if name not in attempts]
    require(not missing, f'drawn theorems not found in SanityChecks.lean: {missing}')
    return Merkle(height, leaves, [attempts[name] for name in MERKLE_VIEWS])


